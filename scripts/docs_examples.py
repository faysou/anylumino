@contextmanager
def jupyterlab():
    """Run a JupyterLab server on a free port and yield its base URL and token."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]

    token = "docsshots"
    LAB_LOG.parent.mkdir(parents=True, exist_ok=True)
    log = LAB_LOG.open("w")
    server = subprocess.Popen(
        [sys.executable, "-m", "jupyterlab", "--no-browser", f"--port={port}", f"--ServerApp.token={token}"],
        stdout=log,
        stderr=subprocess.STDOUT,
    )
    url = f"http://127.0.0.1:{port}"
    try:
        deadline = time.monotonic() + 60
        while True:
            try:
                urllib.request.urlopen(f"{url}/api/status?token={token}", timeout=2)
                break
            except OSError:
                if time.monotonic() > deadline or server.poll() is not None:
                    raise RuntimeError(f"JupyterLab did not start; see {log.name}") from None

                time.sleep(0.5)

        yield url, token
    finally:
        server.terminate()
        server.wait(timeout=30)
        log.close()


def capture_notebook(browser, url: str, token: str, notebook: Path, output: Path, crop: bool) -> list[str]:
    """Run ``notebook`` and save every marked cell's output; return the slugs it skipped."""
    slugs = re.findall(r"# docs-example\(([\w-]+)\)", notebook.read_text())
    # The device scale factor gives retina detail; the notebook-sized viewport
    # keeps examples from stretching across a desktop window.
    viewport = CROP_VIEWPORT if crop else VIEWPORT
    page = browser.new_page(viewport=viewport, device_scale_factor=2)
    skipped = []
    try:
        # A workspace of its own, reset on every run, so JupyterLab opens no
        # notebook that an earlier session left in the default workspace.
        workspace = re.sub(r"\W", "-", notebook.stem)
        page.goto(f"{url}/lab/workspaces/{workspace}/tree/{notebook.as_posix()}?reset&token={token}")
        page.wait_for_function(NOTEBOOK_READY_JS, arg=notebook.name, timeout=60_000)
        page.wait_for_timeout(2000)
        page.click('.jp-NotebookPanel:not(.lm-mod-hidden) [data-command="notebook:restart-run-all"]')
        page.click(".jp-Dialog button.jp-mod-accept")
        page.wait_for_function(NOTEBOOK_IDLE_JS, timeout=600_000, polling=1000)
        errors = page.locator(".jp-OutputArea-output.jp-mod-error").all_inner_texts()
        if errors:
            raise RuntimeError(f"{notebook}: {len(errors)} cells failed: {errors[0][:300]}")

        output.mkdir(parents=True, exist_ok=True)
        if crop:
            page.click("#jp-left-stack-tabs .lm-TabBar-tab.lm-mod-current, .jp-SideBar.jp-mod-left .lm-TabBar-tab.lm-mod-current")
            page.add_style_tag(content=CROP_CSS)

        for slug in slugs:
            state = "scrolled"
            while state == "scrolled":
                state = page.evaluate(REVEAL_CELL_JS, slug)
                page.wait_for_timeout(300)

            # Cells render as they scroll into view, and widgets such as Plotly
            # figures finish their first paint after that.
            page.evaluate(OUTPUT_BOX_JS, [slug, crop])
            page.wait_for_timeout(1500)
            box = page.evaluate(OUTPUT_BOX_JS, [slug, crop])
            if state != "found" or box is None:
                skipped.append(slug)
                continue

            # A tall output grows the viewport instead of spilling into the
            # surrounding JupyterLab chrome.
            needed = int(box["height"]) + 160
            if needed > viewport["height"]:
                page.set_viewport_size({**viewport, "height": needed})
                page.wait_for_timeout(1000)
                box = page.evaluate(OUTPUT_BOX_JS, [slug, crop])

            page.screenshot(path=output / f"{slug}.png", clip=box)
            page.set_viewport_size(viewport)
    finally:
        page.close()

    print(f"{notebook}: {len(slugs) - len(skipped)} of {len(slugs)} captured")

    return skipped


def capture(target: str) -> int:
    from playwright.sync_api import sync_playwright

    if target == "docs":
        write_notebook(read_examples())
        notebook, output, crop = NOTEBOOK, DOCS_DIR / IMAGE_DIR, False
    elif target == "components":
        write_component_notebook()
        notebook, output, crop = COMPONENT_NOTEBOOK, COMPONENT_IMAGE_DIR, True
    else:
        print(__doc__)

        return 1

    with jupyterlab() as (url, token), sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        try:
            skipped = capture_notebook(browser, url, token, notebook, output, crop)
        finally:
            browser.close()

    if skipped:
        print(f"skipped: {', '.join(skipped)}")

    return 1 if skipped else 0


def write_api_images() -> None:
    """Show each class's screenshot under its docstring example, the first Python block of its API page.

    A page's screenshot is named after the page path, such as
    `astryx-surfaces-Stepper.png` for `api/astryx/surfaces/Stepper.mdx`. The
    capture is at twice the CSS pixel size, so the image shows at half its size.
    """
    updated = 0
    for page in sorted(API_DIR.rglob("*.mdx")):
        slug = "-".join(page.relative_to(API_DIR).with_suffix("").parts)
        image = COMPONENT_IMAGE_DIR / f"{slug}.png"
        text = page.read_text()
        start = text.find("```python\n")
        end = text.find("\n```\n", start)
        if not image.exists() or start == -1 or end == -1 or "component-example" in text:
            continue

        link = Path("../" * (len(page.relative_to(DOCS_DIR).parts) - 1)) / image.relative_to(DOCS_DIR)
        name = page.stem
        figure = (
            f"\nimport screenshot from '{link.as_posix()}';\n\n"
            f'<figure className="component-example">\n'
            f"  <img src={{screenshot.src}} width={{screenshot.width / 2}} height={{screenshot.height / 2}} "
            f'alt="{name} example rendered in JupyterLab" />\n'
            f"</figure>\n"
        )
        at = end + len("\n```\n")
        page.write_text(text[:at] + figure + text[at:])
        updated += 1

    print(f"{updated} API pages show a screenshot")


def main() -> int:
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    examples = read_examples()
    if command == "notebook":
        write_notebook(examples)
    elif command == "images":
        write_images(examples)
    elif command == "components":
        write_component_notebook()
    elif command == "api-images":
        write_api_images()
    elif command == "capture":
        return capture(sys.argv[2] if len(sys.argv) > 2 else "")
    elif command == "list":
        for example in examples:
            mark = "shot" if example.screenshot else "   -"
            print(f"{mark} {example.slug}")
    else:
        print(__doc__)

        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
