# The output of the marked cell, scrolled to the top of the viewport. With
# `crop`, the box is the union of what the widget draws, padded evenly: text,
# media and form controls, and elements with a background, border, or shadow.
# Containers that only stretch to the output width do not count, and open
# popovers count even where they extend past the output.
OUTPUT_BOX_JS = """([target, crop]) => {
  const panel = document.querySelector(".jp-NotebookPanel:not(.lm-mod-hidden)");
  const cell = [...panel.querySelectorAll(".jp-CodeCell")].find((node) =>
    (node.querySelector(".jp-InputArea-editor")?.textContent ?? "").includes(`# docs-example(${target})`));
  const output = cell?.querySelector(".jp-OutputArea-output");
  if (!output) return null;
  if (crop) {
    for (const marked of document.querySelectorAll(".docs-shot-target")) marked.classList.remove("docs-shot-target");
    cell.classList.add("docs-shot-target");
  }
  output.scrollIntoView({ block: crop ? "center" : "start" });
  const rect = output.getBoundingClientRect();
  if (rect.width < 8 || rect.height < 8) return null;
  if (!crop) return { x: rect.x, y: rect.y, width: rect.width, height: rect.height };
  const drawn = new Set(["IMG", "SVG", "CANVAS", "VIDEO", "INPUT", "TEXTAREA", "SELECT", "BUTTON"]);
  let box = null;
  // A rectangle counts only where its scrolling or clipping ancestors show it, so
  // rows scrolled out of a scroll box do not stretch the image.
  const clipped = (node, r) => {
    let { left, top, right, bottom } = r;
    for (let item = node.parentElement; item && item !== output; item = item.parentElement) {
      const style = getComputedStyle(item);
      if (style.overflowX === "visible" && style.overflowY === "visible") continue;
      const c = item.getBoundingClientRect();
      if (style.overflowX !== "visible") { left = Math.max(left, c.left); right = Math.min(right, c.right); }
      if (style.overflowY !== "visible") { top = Math.max(top, c.top); bottom = Math.min(bottom, c.bottom); }
    }
    return { left, top, right, bottom, width: right - left, height: bottom - top };
  };
  const add = (r) => {
    if (r.width < 1 || r.height < 1) return;
    box = box
      ? { left: Math.min(box.left, r.left), top: Math.min(box.top, r.top), right: Math.max(box.right, r.right), bottom: Math.max(box.bottom, r.bottom) }
      : { left: r.left, top: r.top, right: r.right, bottom: r.bottom };
  };
  const visible = (node) => {
    for (let item = node; item && item !== output; item = item.parentElement) {
      const style = getComputedStyle(item);
      if (style.visibility === "hidden" || style.display === "none" || style.opacity === "0") return false;
    }
    return true;
  };
  for (const node of output.querySelectorAll("*")) {
    if (!visible(node)) continue;
    const style = getComputedStyle(node);
    const painted = drawn.has(node.tagName.toUpperCase())
      || style.backgroundColor !== "rgba(0, 0, 0, 0)"
      || style.backgroundImage !== "none"
      || parseFloat(style.borderTopWidth) + parseFloat(style.borderBottomWidth)
        + parseFloat(style.borderLeftWidth) + parseFloat(style.borderRightWidth) > 0
      || style.boxShadow !== "none";
    if (painted) add(clipped(node, node.getBoundingClientRect()));
  }
  const walker = document.createTreeWalker(output, NodeFilter.SHOW_TEXT);
  for (let text = walker.nextNode(); text; text = walker.nextNode()) {
    if (!text.textContent.trim() || !visible(text.parentElement)) continue;
    const range = document.createRange();
    range.selectNodeContents(text);
    for (const r of range.getClientRects()) add(clipped(text.parentElement, r));
  }
  if (!box) return null;
  const pad = 16;
  const left = Math.max(0, box.left - pad);
  const top = Math.max(0, box.top - pad);
  return { x: left, y: top, width: box.right + pad - left, height: box.bottom + pad - top };
}"""


