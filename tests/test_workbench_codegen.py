import asyncio

import pytest

from anylumino import astryx as ax
from anylumino.workbench import App, Event, codegen, openui
from anylumino.workbench.catalog import go


PROGRAM = """root = VBox([title, form, card, tabs])
title = Heading("Sales", 2)
form = HBox([region, go, ask])
region = TextInput("Region", "", "Enter region", @Callback("on_region"))
go = Button("Run", @Callback("on_run", "q3"), "primary")
ask = Button("Explain", Action([@Callback("on_run"), @ToAssistant("Explain this", "ctx")]))
card = Card([Text("inline"), Markdown("**bold**")])
tabs = TabPanel([table, chart], ["Rows", "Chart"])
table = Table([{"region": "EMEA", "revenue": 1.5}], ["region", "revenue"], {sortable: true, density: "compact"})
chart = Widget("fig")"""

EXPECTED = '''"""Generated by the anylumino workbench from an OpenUI program."""

import anylumino as al
import anylumino.astryx as ax
from anylumino.workbench import Event, View


class UI(View):
    """The generated view of ``app``, with one attribute per OpenUI statement."""

    def __init__(self, app):
        self.app = app
        self.title = ax.Heading(text='Sales', level=2)
        self.region = ax.TextInput(label='Region', value='', placeholder='Enter region')
        self.go = ax.Button(label='Run', variant='primary')
        self.ask = ax.Button(label='Explain')
        self.form = ax.Stack(children=[self.region, self.go, self.ask], direction='horizontal')
        _text_1 = ax.Text(text='inline')
        _markdown_2 = ax.Markdown(text='**bold**')
        self.card = ax.Card(children=[_text_1, _markdown_2])
        self.table = ax.Table(rows=[{'region': 'EMEA', 'revenue': 1.5}], columns=['region', 'revenue'], sortable=True, density='compact')
        self.chart = app.fig
        self.tabs = al.TabPanel(widgets=[self.table, self.chart], titles=['Rows', 'Chart'])
        self.root = ax.Stack(children=[self.title, self.form, self.card, self.tabs], direction='vertical')

        def region_on_change(_widget, value=None):
            app.call('on_region', Event('region', value, None))

        self.region.on_action(region_on_change)

        def go_action(_widget, value=None):
            app.call('on_run', Event('go', value, 'q3'))

        self.go.on_click(go_action)

        def ask_action(_widget, value=None):
            app.call('on_run', Event('ask', value, None))
            app.ask_agent('Explain this', 'ctx')

        self.ask.on_click(ask_action)

        self.widget = self.root
        app.set_ui(self)
'''


def parsed(program):
    result = asyncio.run(openui.parse(program))
    assert result["errors"] == []

    return result


class RecordingApp(App):
    def __init__(self, **namespace):
        super().__init__(**namespace)
        self.events = []
        self.asks = []

    def on_region(self, event):
        self.events.append(("on_region", event))

    def on_run(self, event):
        self.events.append(("on_run", event))

    def ask_agent(self, message, context=None):
        self.asks.append((message, context))


def ui_class(source):
    module = {}
    exec(compile(source, "ui.py", "exec"), module)

    return module["UI"]


def test_generate_matches_snapshot():
    fig = ax.Text("figure")
    assert codegen.generate(parsed(PROGRAM), {"on_region", "on_run"}, {"fig": fig}) == EXPECTED


def test_generate_is_deterministic():
    result = parsed(PROGRAM)
    first = codegen.generate(result, {"on_region", "on_run"}, {"fig": None})
    assert codegen.generate(result, {"on_region", "on_run"}, {"fig": None}) == first


def test_generated_ui_builds_every_named_widget():
    fig = ax.Text("figure")
    app = RecordingApp(fig=fig)
    ui = ui_class(EXPECTED)(app)

    assert (ui.app, app.ui, ui.widget) == (app, ui, ui.root)
    assert ui.chart is fig
    assert ui.tabs.widgets == [ui.table, fig]
    assert ui.root.widgets == [ui.title, ui.form, ui.card, ui.tabs]
    assert ui.form.widgets == [ui.region, ui.go, ui.ask]
    assert ui.title.text == "Sales"
    assert (ui.table.sortable, ui.table.props["density"]) == (True, "compact")


def test_generated_ui_sends_events_to_the_app():
    app = RecordingApp(fig=ax.Text("figure"))
    ui = ui_class(EXPECTED)(app)

    ui.go._handle_frontend_message(ui.go, {"type": "click"}, None)
    ui.region.value = "EMEA"
    ui.ask._handle_frontend_message(ui.ask, {"type": "click"}, None)

    assert app.events == [
        ("on_run", Event("go", None, "q3")),
        ("on_region", Event("region", "EMEA", None)),
        ("on_run", Event("ask", None, None)),
    ]
    assert app.asks == [("Explain this", "ctx")]


@pytest.mark.parametrize(
    ("program", "handlers", "namespace", "message"),
    [
        ('root = VBox([go])\ngo = Button("Run", @Callback("on_run"))', set(), {}, "go.action: callback 'on_run' is not defined"),
        ('root = VBox([chart])\nchart = Widget("fig")', set(), {}, "chart: no widget named 'fig' in the namespace"),
        ('root = VBox([go])\ngo = Button("Docs", @OpenUrl("https://x"))', set(), {}, "go.action: unsupported action open_url"),
        ('root = VBox([widget])\nwidget = Text("a")', set(), {}, "widget: the generated UI uses this name; rename the statement"),
        ('root = VBox([app])\napp = Text("a")', set(), {}, "app: the generated UI uses this name; rename the statement"),
        ('root = VBox([t])\nt = Table([], [], {sorted: true})', set(), {}, "t.options: Table has no option 'sorted'"),
        ('$sel = "a"\nroot = VBox([Text($sel)])', set(), {}, r"\$state variables is not supported: \$sel"),
    ],
    ids=["missing-handler", "missing-namespace-widget", "unsupported-action", "widget-name", "app-name", "unknown-option", "state"],
)
def test_generate_rejects_with_named_error(program, handlers, namespace, message):
    result = asyncio.run(openui.parse(program))
    with pytest.raises(codegen.GenerationError, match=f"^{message}$"):
        codegen.generate(result, handlers, namespace)


def test_generate_rejects_a_program_without_root():
    with pytest.raises(codegen.GenerationError, match="^The program has no root component.$"):
        codegen.generate({"root": None}, set(), {})


def test_plot_builds_a_figure_and_imports_plotly():
    program = 'root = VBox([chart])\nchart = Plot({height: 320, title: {text: "Revenue"}})'

    source = codegen.generate(parsed(program), set(), {})
    ui = ui_class(source)(RecordingApp())

    assert source == '''"""Generated by the anylumino workbench from an OpenUI program."""

import anylumino as al
import anylumino.astryx as ax
import plotly.graph_objects as go
from anylumino.workbench import Event, View


class UI(View):
    """The generated view of ``app``, with one attribute per OpenUI statement."""

    def __init__(self, app):
        self.app = app
        self.chart = go.FigureWidget(layout={'height': 320, 'title': {'text': 'Revenue'}})
        self.root = ax.Stack(children=[self.chart], direction='vertical')

        self.widget = self.root
        app.set_ui(self)
'''
    assert isinstance(ui.chart, go.FigureWidget)
    assert (ui.chart.layout.height, ui.chart.layout.title.text, ui.chart.data) == (320, "Revenue", ())
    assert ui.root.widgets == [ui.chart]


def test_app_frame_components_build_and_send_events():
    program = """root = AppShell([layout], [top], [side])
top = TopNav(["Orders", {label: "More", items: ["Export"]}], "Orders", [Button("Help"), Toast()])
side = SideNav(["Overview", {type: "section", title: "Desk", items: ["Fills"]}], "Overview", @Callback("on_run"))
layout = Layout([steps, editor], [Timer()], [actions], null, [RichTextView("**done**")])
steps = Stepper(["Draft", "Send"], 1)
editor = RichTextEditor("Notes", "# Plan", @Callback("on_region"))
actions = OverflowList(["Refresh", "Export"], @Callback("on_run", "bar"))"""

    source = codegen.generate(parsed(program), {"on_region", "on_run"}, {})
    app = RecordingApp()
    ui = ui_class(source)(app)
    ui.side.value = "Fills"
    ui.editor.value = "# Plan\n\nShip"
    ui.actions._handle_frontend_message(ui.actions, {"type": "click", "value": "Export"}, None)

    assert ui.root.child_keys == ["content", "top_nav", "side_nav"]
    assert [ui.root.get_owner(key) for key in ("content", "top_nav", "side_nav")] == [ui.layout, ui.top, ui.side]
    assert ui.top.child_keys == ["end"]
    assert ui.top.get_owner("end").props["direction"] == "horizontal"
    assert ui.layout.child_keys == ["content", "header", "start", "footer"]
    assert (ui.steps.value, ui.editor.label, ui.editor.value) == (1, "Notes", "# Plan\n\nShip")
    assert app.events == [
        ("on_run", Event("side", "Fills", None)),
        ("on_region", Event("editor", "# Plan\n\nShip", None)),
        ("on_run", Event("actions", "Export", "bar")),
    ]
