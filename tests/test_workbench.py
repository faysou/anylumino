SETUP_PROGRAM = """root = VBox([region, table])
region = Selector([], "All", "Region")
table = Table([], ["region", "revenue"])"""


def test_setup_fills_widgets_from_the_namespace(agent_reply, tmp_path, sales):
    callbacks = app_callbacks(
        "    def setup(self):\n"
        "        self.ui.table.set_rows(self.sales.to_dict('records'))\n"
        "        self.ui.region.items = sorted(self.sales['region'])\n"
    )
    agent_reply(reply("Done.", SETUP_PROGRAM, callbacks))
    workbench = Workbench(agent="codex", namespace={"sales": sales}, cwd=tmp_path)
    workbench.submit("Build it")
    region, table = workbench.ui_host.widgets[0].root.widgets

    assert region.items == ["APAC", "EMEA"]
    assert [(row["region"], row["revenue"]) for row in table.rows] == [("EMEA", 1.5), ("APAC", 2.0)]
    assert workbench.last_error == ""


