def test_message_posted_during_a_turn_is_kept(agent_reply, tmp_path, monkeypatch):
    agent_reply(reply("Done.", PROGRAM, CALLBACKS))
    monkeypatch.setenv("FAKE_SLEEP", "0.5")
    workbench = Workbench(agent="codex", cwd=tmp_path)

    async def scenario():
        workbench.submit("Build it")
        while len(workbench.chat.messages) < 2 or workbench.chat.messages[1]["content"] == "":
            await asyncio.sleep(0.01)

        workbench.add_message("system", "Callback `on_fail` raised KeyError: 'region'")
        while workbench.tasks:
            await asyncio.sleep(0.01)

    asyncio.run(scenario())

    assert workbench.chat.messages == [
        {"role": "user", "content": "Build it", "status": "sent"},
        {"role": "assistant", "content": "Done."},
        {"role": "system", "content": "Callback `on_fail` raised KeyError: 'region'"},
    ]


