    agent_reply(reply("Done.", 'root = VBox([title])\ntitle = Heading("Sales")', callbacks))
    workbench = Workbench(agent="codex", namespace=namespace, cwd=tmp_path)
    workbench.submit("Build it")

    assert workbench.chat.messages[-1] == {
        "role": "system",
        "content": f"The reply was not applied; the UI is unchanged. {message}",
    }
