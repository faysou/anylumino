SETUP_PROGRAM = """root = VBox([region, table])
region = Selector([], "All", "Region")
table = Table([], ["region", "revenue"])"""


def test_setup_fills_widgets_from_the_namespace(agent_reply, tmp_path, sales):
    callbacks = """def setup(widgets):
    widgets["table"].set_rows(sales.to_dict("records"))
    widgets["region"].items = sorted(sales["region"])
"""
    agent_reply(reply("Done.", SETUP_PROGRAM, callbacks))
    workbench = Workbench(agent="codex", namespace={"sales": sales}, cwd=tmp_path)
    workbench.submit("Build it")
    region, table = workbench.ui_host.widgets[0].widgets

    assert region.items == ["APAC", "EMEA"]
    assert [(row["region"], row["revenue"]) for row in table.rows] == [("EMEA", 1.5), ("APAC", 2.0)]
    assert workbench.last_error == ""


def test_raising_setup_is_reported_and_the_ui_still_applies(agent_reply, tmp_path):
    agent_reply(reply("Done.", SETUP_PROGRAM, "def setup(widgets):\n    raise ValueError('no data')\n"))
    workbench = Workbench(agent="codex", cwd=tmp_path)
    workbench.submit("Build it")

    assert workbench.chat.messages[-1] == {"role": "system", "content": "Callback `setup` raised ValueError: no data"}
    assert workbench.state.program == SETUP_PROGRAM


