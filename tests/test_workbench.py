PROGRAM = """root = VBox([title, go, fail])
title = Heading("Sales")
go = Button("Total", @Callback("on_total"))
fail = Button("Fail", @Callback("on_fail"))"""

CALLBACKS = """from anylumino.workbench import App


class SalesApp(App):
    def on_total(self, event):
        self.ui.title.text = f"Total {self.sales['revenue'].sum()}"

    def on_fail(self, event):
        raise KeyError("region")
"""


def app_callbacks(body):
    """Wrap method source in the App subclass a callbacks block defines."""

    return "from anylumino.workbench import App\n\n\nclass TestApp(App):\n" + body


def reply(prose, program=None, callbacks=None):
    parts = [prose]
    if program is not None:
        parts.append(f"```openui-lang\n{program}\n```")

    if callbacks is not None:
        parts.append(f"```python\n{callbacks}```")

    return "\n".join(parts)


@pytest.fixture
def sales():
    return pd.DataFrame({"region": ["EMEA", "APAC"], "revenue": [1.5, 2.0]})


def code(workbench):
    return {key: view.props["code"] for key, view in workbench.code_views.items()}


def click(widget):
    widget._handle_frontend_message(widget, {"type": "click"}, None)


def test_fresh_workbench_layout(tmp_path):
    workbench = Workbench(agent="codex", cwd=tmp_path)

    chat_column, tabs = workbench.widgets
    header, chat = chat_column.widgets
    assert tabs is workbench.tabs
    assert chat is workbench.chat
    assert (tabs.child_keys, tabs.titles, tabs.selected_index) == (
        ["ui", "openui", "ui_code", "callbacks"],
        ["UI", "OpenUI", "UI code", "Callbacks"],
        0,
    )
    agent, session, dot, caption, export, dialog = header.widgets
    assert (agent.label, session.label, dot.label, caption.text) == ("codex", "unsaved", "Ready", "Ready")
    assert (export.label, export.disabled) == ("Export", True)
    assert (dialog is workbench.export_dialog, dialog.is_open) == (True, False)
    assert workbench.suppress_shortcuts is True
    (empty,) = workbench.ui_host.widgets
    assert isinstance(empty, ax.EmptyState)
    assert code(workbench) == {"openui": "", "ui_code": "", "callbacks": ""}
    assert all(isinstance(view, ax.CodeBlock) for view in workbench.code_views.values())


def test_successful_turn_updates_all_tabs(agent_reply, tmp_path, sales):
    agent_reply(reply("Here is a sales panel.", PROGRAM, CALLBACKS))
    workbench = Workbench(agent="codex", namespace={"sales": sales}, cwd=tmp_path)

    workbench.chat._handle_frontend_message(workbench.chat, {"type": "submit", "value": "Build it"}, None)

    assert workbench.chat.messages == [
        {"role": "user", "content": "Build it", "status": "sent"},
        {"role": "assistant", "content": "Here is a sales panel."},
    ]
    assert code(workbench) == {"openui": PROGRAM, "ui_code": workbench.ui_code, "callbacks": CALLBACKS}
    assert workbench.ui_code.startswith('"""Generated by the anylumino workbench')
    (ui,) = workbench.ui_host.widgets
    title, go, _fail = ui.root.widgets
    assert (type(ui).__name__, ui.widgets, ui.app.ui, ui.app.sales) == ("UI", [ui.root], ui, sales)
    assert isinstance(ui.root, ax.Stack)
    click(go)
    assert title.text == "Total 3.5"
    assert workbench.chat.is_streaming is False
    assert workbench.runner.session_id == "thread-1"


def test_failing_callbacks_keep_previous_state(agent_reply, tmp_path, sales):
    agent_reply(reply("First.", PROGRAM, CALLBACKS))
    workbench = Workbench(agent="codex", namespace={"sales": sales}, cwd=tmp_path)
    workbench.submit("Build it")
    before = (code(workbench), workbench.ui_host.widgets)

    agent_reply(reply("Broken.", None, "def on_total(event, widgets):\n    return (\n"))
    workbench.submit("Change it")

    assert (code(workbench), workbench.ui_host.widgets) == before
    assert workbench.chat.messages[-1] == {
        "role": "system",
        "content": "The reply was not applied; the UI is unchanged. "
        "Callbacks failed to compile: '(' was never closed (line 2)",
    }
    agent_reply("Noted.")
    workbench.submit("Why?")
    prompt = agent_reply.calls()[-1]["stdin"]
    assert "Your previous reply was not applied: Callbacks failed to compile: '(' was never closed (line 2)" in prompt
    assert f"Current program:\n```openui-lang\n{PROGRAM}\n```" in prompt


