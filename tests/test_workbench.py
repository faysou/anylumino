def test_stop_marks_the_reply_and_keeps_the_ui(agent_reply, tmp_path, monkeypatch):
    agent_reply(reply("Partial.", PROGRAM, CALLBACKS))
    monkeypatch.setenv("FAKE_SLEEP", "30")

    async def scenario():
        workbench = Workbench(agent="codex", cwd=tmp_path)
        workbench.submit("Build it")
        while not workbench.runner.running or workbench.chat.messages[-1]["content"] == "":
            await asyncio.sleep(0.01)
        running = (workbench.status.label, workbench.status_text.text, workbench.status.variant)
        workbench.chat._handle_frontend_message(workbench.chat, {"type": "stop"}, None)
        while workbench.tasks:
            await asyncio.sleep(0.01)
        return workbench, running

    workbench, running = asyncio.run(scenario())
    assert running == ("Running", "Running", "accent")
    assert (workbench.status.label, workbench.status_text.text, workbench.status.variant) == ("Ready", "Ready", "neutral")
    assert workbench.chat.messages[-1]["status"] == "stopped"
    assert code(workbench) == {"openui": "", "ui_code": "", "callbacks": ""}
    (empty,) = workbench.ui_host.widgets
    assert isinstance(empty, ax.EmptyState)
    assert workbench.chat.is_streaming is False


def test_session_restores_and_resumes(agent_reply, tmp_path, sales):
    agent_reply(reply("First.", PROGRAM, CALLBACKS))
    first = Workbench(agent="codex", session="sales", namespace={"sales": sales}, cwd=tmp_path)
    first.submit("Build it")
    agent_reply(reply("Renamed.", 'title = Heading("Revenue")'))
    first.submit("Rename")

    restored = Workbench(agent="claude", session="sales", namespace={"sales": sales})

    assert restored.state.agent == "codex"
    assert restored.chat.messages == first.chat.messages
    assert code(restored) == code(first)
    assert 'title = Heading("Revenue")' in code(restored)["openui"]
    assert restored.ui_host.widgets[0].widgets[0].text == "Revenue"
    agent_reply("Hello again.")
    restored.submit("Hi")
    assert agent_reply.calls()[-1]["argv"][:3] == ["exec", "resume", "thread-1"]
    assert agent_reply.calls()[-1]["cwd"] == str(tmp_path.resolve())


def test_session_restore_with_missing_namespace_widget(agent_reply, tmp_path):
    program = 'root = VBox([chart])\nchart = Widget("fig")'
    agent_reply(reply("Chart.", program, "x = 1\n"))
    Workbench(agent="codex", session="charts", namespace={"fig": ax.Text("figure")}, cwd=tmp_path).submit("Chart")

    restored = Workbench(session="charts")

    (empty,) = restored.ui_host.widgets
    assert isinstance(empty, ax.EmptyState)
    assert empty.props["description"] == "UI code: chart: no widget named 'fig' in the namespace"
    assert code(restored) == {"openui": program, "ui_code": "", "callbacks": "x = 1\n"}
    assert [message["role"] for message in restored.chat.messages] == ["user", "assistant"]


def test_openui_tool_failure_is_reported_and_ends_the_turn(agent_reply, tmp_path, monkeypatch):
    async def failing_merge(current, patch):
        raise openui.OpenUIError("OpenUI tool failed (1): boom")

    monkeypatch.setattr(openui, "merge", failing_merge)
    agent_reply(reply("Here.", PROGRAM, CALLBACKS))
    workbench = Workbench(agent="codex", cwd=tmp_path)
    workbench.submit("Build it")

    assert workbench.chat.messages[-1] == {
        "role": "system",
        "content": "The reply was not applied; the UI is unchanged. OpenUI tool failed (1): boom",
    }
    assert workbench.chat.is_streaming is False
    assert (workbench.status.label, workbench.status_text.text) == ("Ready", "Ready")
